import { expect, test } from "@playwright/test";

test("真实对话、运行期间设置、历史恢复与停止", async ({ page, request }) => {
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  page.on("console", (message) => { if (message.type() === "error") errors.push(message.text()); });
  await page.goto("/");
  await page.getByRole("textbox", { name: "消息输入框" }).fill("端到端测试：请用一句话说明为什么天空是蓝色的。");
  const created = page.waitForResponse((response) => response.request().method() === "POST" && /\/runs$/.test(response.url()));
  await page.getByRole("button", { name: "发送", exact: true }).click();
  const run = await (await created).json();
  expect(run.run_id).toBeTruthy();
  await expect(page.getByRole("button", { name: "停止生成" })).toBeVisible();
  await page.getByRole("combobox", { name: "思考深度" }).click();
  const savedReasoning = page.waitForResponse((response) => response.url().endsWith(`/conversations/${run.conversation_id}/settings`));
  await page.getByRole("option", { name: "轻度思考", exact: true }).click();
  expect((await savedReasoning).status()).toBe(200);
  await page.getByRole("combobox", { name: "权限模式" }).click();
  const savedPermission = page.waitForResponse((response) => response.url().endsWith(`/conversations/${run.conversation_id}/settings`));
  await page.getByRole("option", { name: "自动批准", exact: true }).click();
  expect((await savedPermission).status()).toBe(200);
  await expect(page.getByRole("button", { name: "停止生成" })).toBeHidden({ timeout: 120_000 });
  await expect(page.locator(".message-assistant .markdown-body")).toContainText(/蓝|散射/);
  const detail = await (await request.get(`/api/workspaces/default/runs/${run.run_id}`)).json();
  expect(detail.status).toMatch(/^completed/);
  expect(detail.reasoning_level).toBe("low");
  expect(detail.permission_mode).toBe("auto");
  const history = await (await request.get(`/api/conversations/${run.conversation_id}`)).json();
  expect(history.messages).toHaveLength(2);
  const listed = await (await request.get("/api/conversations")).json();
  expect(listed.some((item: { id: string }) => item.id === run.conversation_id)).toBe(true);
  await page.reload();
  await expect(page.locator(".message-assistant .markdown-body")).toContainText(/蓝|散射/);
  await expect(page.getByRole("combobox", { name: "思考深度" })).toContainText("轻度思考");
  await page.getByRole("textbox", { name: "消息输入框" }).fill("把刚才的解释再缩短，控制在二十个字以内。");
  const followup = page.waitForResponse((response) => response.request().method() === "POST" && /\/runs$/.test(response.url()));
  await page.getByRole("button", { name: "发送", exact: true }).click();
  await followup;
  await expect(page.getByRole("button", { name: "停止生成" })).toBeHidden({ timeout: 120_000 });
  await expect(page.locator(".message-assistant .markdown-body").last()).toContainText(/蓝|散射/);
  await page.getByRole("textbox", { name: "消息输入框" }).fill("请详细解释光的散射，至少列出十项观察和原理。");
  const nextCreated = page.waitForResponse((response) => response.request().method() === "POST" && /\/runs$/.test(response.url()));
  await page.getByRole("button", { name: "发送", exact: true }).click();
  const nextRun = await (await nextCreated).json();
  await page.getByRole("button", { name: "停止生成" }).click();
  await expect.poll(async () => (await (await request.get(`/api/workspaces/default/runs/${nextRun.run_id}`)).json()).status).toBe("cancelled");
  await expect(page.getByRole("button", { name: "停止生成" })).toBeHidden();
  await page.locator(".message-content.user").first().hover();
  await page.getByRole("button", { name: "编辑这条提问", exact: true }).first().click();
  await expect(page.getByRole("textbox", { name: "消息输入框" })).toHaveValue("端到端测试：请用一句话说明为什么天空是蓝色的。");
  await expect.poll(async () => (await (await request.get(`/api/conversations/${run.conversation_id}`)).json()).messages.length).toBe(0);
  await page.getByRole("textbox", { name: "消息输入框" }).fill("请用一句话解释彩虹。");
  const edited = page.waitForResponse((response) => response.request().method() === "POST" && /\/runs$/.test(response.url()));
  await page.getByRole("button", { name: "发送", exact: true }).click();
  await edited;
  await expect(page.getByRole("button", { name: "停止生成" })).toBeHidden({ timeout: 120_000 });
  await expect(page.locator(".message-assistant .markdown-body")).toContainText(/彩虹|折射/);
  await page.reload();
  await expect(page.locator(".message-user")).toHaveCount(1);
  await expect(page.locator(".message-assistant .markdown-body")).toContainText(/彩虹|折射/);
  expect(errors).toEqual([]);
});

